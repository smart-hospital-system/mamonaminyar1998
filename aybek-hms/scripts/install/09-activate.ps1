<#
.SYNOPSIS
  09 - Activation wizard: turn the 14-day trial into a licensed installation.

.DESCRIPTION
  Explains the licence, checks the format and checksum of a serial locally
  (no internet), then activates it against the running hospital. Serials are
  generated by the owner on the Licence page and look like
  AYBK-XXXX-XXXX-XXXX-CCCC.

.EXAMPLE
  .\scripts\install\09-activate.ps1
  .\scripts\install\09-activate.ps1 -Serial "AYBK-HSU5-2QHP-A9KH-MAGL"
  .\scripts\install\09-activate.ps1 -Generate -Plan hospital -Count 3
#>

param(
    [string]$Path,
    [string]$Serial,
    [switch]$Generate,
    [ValidateSet("trial", "clinic", "hospital", "enterprise")]
    [string]$Plan = "hospital",
    [int]$Count = 1
)

. "$PSScriptRoot\_common.ps1"

Write-Banner "AYBEK HOSPITAL - ACTIVATION WIZARD"

$root = Get-HmsRoot -Override $Path
Set-Location -LiteralPath $root

if ($Generate) {
    $serialFile = Join-Path $root "aybek-hms\SERIALS.txt"
    Write-Step "Generating $Count $Plan serial(s)"
    $lines = & npx tsx scripts/generate-serials.ts $Plan $Count
    if ($LASTEXITCODE -ne 0) { Stop-WithMessage "Serial generation failed." "Run: npx tsx scripts/generate-serials.ts $Plan $Count" }
    foreach ($line in $lines) { if ($line) { Write-Host "  $line" -ForegroundColor Green } }
    $serialFile = Join-Path $root "aybek-hms\SERIALS.txt"
    Write-Ok "Serials also appended to $serialFile - keep that file private."
    Read-Host "Press Enter to close" | Out-Null
    exit 0
}

Write-Host ""
Write-Host "  How the licence works" -ForegroundColor Cyan
Write-Host "  ---------------------"
Write-Host "  - Every copy runs a 14-day trial that starts with the first sign-in."
Write-Host "  - A serial unlocks the hospital permanently on THIS computer."
Write-Host "  - The last group of the serial is a checksum, so typos are caught offline."
Write-Host "  - Patient data is never deleted when a trial expires - the hospital becomes read-only."
Write-Host ""

if (-not $Serial) {
    $Serial = (Read-Host "Paste the serial number (leave empty to cancel)").Trim().ToUpper()
    if (-not $Serial) { Write-Info "Cancelled - nothing changed."; exit 0 }
}

if ($Serial -notmatch "^AYBK(-[A-Z0-9]{4}){3}-[A-Z0-9]{4}$") {
    Stop-WithMessage ""$Serial" does not look like an Aybek serial." "The format is AYBK-XXXX-XXXX-XXXX-XXXX. Copy it exactly from your certificate."
}

Write-Step "Checking the hospital server"
$base = "http://localhost:3000"
try {
    $health = Invoke-WebRequest -Uri "$base/hms/login" -UseBasicParsing -TimeoutSec 5
    Write-Ok "Server answered ($($health.StatusCode))"
} catch {
    Stop-WithMessage "The hospital server is not running." "Start it first with .\scripts\install\04-start.ps1, then run this wizard again."
}

Write-Host ""
if (-not (Confirm-Action "Activate this computer with $Serial ?" -DefaultYes)) { Write-Info "Cancelled."; exit 0 }

Write-Step "Activating"
try {
    $payload = @{ action = "activate"; serial = $Serial; machine = $env:COMPUTERNAME } | ConvertTo-Json
    $response = Invoke-RestMethod -Uri "$base/api/hms/license" -Method Post -ContentType "application/json" -Body $payload -SessionVariable session -ErrorAction Stop
    if ($response.ok) {
        Write-Ok "Activated - $($response.state.plan)"
        Write-Info "Open http://localhost:3000/hms and the trial banner will be gone."
    } else {
        if ($response.error) { Write-Warn $response.error } else { Write-Warn "The server rejected the serial." }
    }
} catch {
    Write-Warn "The request needs an administrator session."
    Write-Info "Sign in at http://localhost:3000/hms/login as doctor@aybek.hospital, then open /hms/activate and paste the serial there."
    Write-Info "That page shows the same result with a clear message."
}

Write-Banner "WIZARD FINISHED"
Write-Host ""
Read-Host "Press Enter to close" | Out-Null
