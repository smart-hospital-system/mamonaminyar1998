import crypto from "node:crypto";
import { hAll, hGet, hNow, hRun, hUid, getSection, saveSettings } from "./db";

/**
 * Offline-first licence keys.
 *
 * Every serial is self-verifying: the last group is a checksum derived from the
 * first three groups plus a build secret, so activation works with no internet
 * connection and no licence server. The owner holds the generator (see
 * `generateSerial`), which is only reachable from the admin console and the
 * PowerShell `06-activate.ps1` wizard.
 */

const SECRET = process.env.AYBEK_LICENSE_SECRET ?? "aybek-hms::2026::ten-bed-surgical";
const ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"; // no I, O, 0, 1
const PREFIX = "AYBK";
const TRIAL_DAYS = 14;

function checksum(body: string) {
  const digest = crypto.createHash("sha256").update(`${SECRET}|${body}`).digest();
  let out = "";
  for (let i = 0; i < 4; i++) out += ALPHABET[digest[i] % ALPHABET.length];
  return out;
}

function randomGroup() {
  let out = "";
  for (let i = 0; i < 4; i++) out += ALPHABET[crypto.randomInt(ALPHABET.length)];
  return out;
}

export type SerialPlan = "trial" | "clinic" | "hospital" | "enterprise";

const PLAN_LABEL: Record<SerialPlan, string> = {
  trial: "Trial",
  clinic: "Clinic Edition",
  hospital: "Hospital Edition",
  enterprise: "Enterprise Edition",
};

const PLAN_SEATS: Record<SerialPlan, number> = { trial: 3, clinic: 10, hospital: 40, enterprise: 250 };

export function generateSerial(plan: SerialPlan = "hospital") {
  const body = `${randomGroup()}-${randomGroup()}-${randomGroup()}`;
  const serial = `${PREFIX}-${body}-${checksum(body)}`;
  hRun(
    "INSERT INTO hms_licenses (id, serial, plan, seats, issued_at, status, note) VALUES (?,?,?,?,?,?,?)",
    [hUid("lic"), serial, PLAN_LABEL[plan], PLAN_SEATS[plan], hNow(), "issued", `Generated by owner console for ${PLAN_LABEL[plan]}`]
  );
  return { serial, plan: PLAN_LABEL[plan], seats: PLAN_SEATS[plan] };
}

export function validateSerial(raw: string) {
  const serial = raw.trim().toUpperCase().replace(/\s+/g, "");
  const match = /^AYBK-([A-Z0-9]{4})-([A-Z0-9]{4})-([A-Z0-9]{4})-([A-Z0-9]{4})$/.exec(serial);
  if (!match) return { valid: false as const, reason: "Format must be AYBK-XXXX-XXXX-XXXX-XXXX." };
  const body = `${match[1]}-${match[2]}-${match[3]}`;
  if (checksum(body) !== match[4]) {
    return { valid: false as const, reason: "Checksum mismatch — this serial was not issued by Aybek." };
  }
  const existing = hGet<{ status: string; plan: string; hospital: string | null }>(
    "SELECT status, plan, hospital FROM hms_licenses WHERE serial = ?",
    [serial]
  );
  if (existing?.status === "activated" && existing.hospital) {
    return { valid: false as const, reason: `Already activated for ${existing.hospital}. Ask the owner to issue a new seat.` };
  }
  return { valid: true as const, serial, plan: existing?.plan ?? "Hospital Edition" };
}

export function activate(serialRaw: string, hospital: string, machine: string) {
  const checked = validateSerial(serialRaw);
  if (!checked.valid) return { ok: false as const, error: checked.reason };
  // The seat count travels with the plan, not with a hard-coded number.
  const planKey = (Object.keys(PLAN_LABEL) as SerialPlan[]).find((k) => PLAN_LABEL[k] === checked.plan) ?? "hospital";
  const seats = PLAN_SEATS[planKey];

  const existing = hGet<{ id: string }>("SELECT id FROM hms_licenses WHERE serial = ?", [checked.serial]);
  if (existing) {
    hRun(
      "UPDATE hms_licenses SET status = 'activated', activated_at = ?, hospital = ?, machine = ? WHERE serial = ?",
      [hNow(), hospital, machine, checked.serial]
    );
  } else {
    hRun(
      "INSERT INTO hms_licenses (id, serial, plan, seats, issued_at, activated_at, hospital, machine, status) VALUES (?,?,?,?,?,?,?,?, 'activated')",
      [hUid("lic"), checked.serial, checked.plan, seats, hNow(), hNow(), hospital, machine]
    );
  }
  saveSettings("license", {
    status: "active",
    serial: checked.serial,
    plan: checked.plan,
    seats,
    activated_at: hNow(),
    machine,
  });
  return { ok: true as const, serial: checked.serial, plan: checked.plan };
}

export type LicenseState = {
  status: "trial" | "active" | "expired" | "grace";
  plan: string;
  serial: string;
  daysLeft: number;
  seats: number;
  activatedAt: string;
  owner: string;
  machine: string;
};

export function licenseState(): LicenseState {
  const lic = getSection<Record<string, unknown>>("license");
  const status = String(lic.status ?? "trial");
  const activatedAt = String(lic.activated_at ?? "");
  if (status === "revoked") {
    return {
      status: "expired",
      plan: `${String(lic.plan ?? "Hospital Edition")} — revoked`,
      serial: String(lic.serial ?? ""),
      daysLeft: 0,
      seats: 0,
      activatedAt,
      owner: String(lic.owner ?? "Dr. Mamon Aminyar"),
      machine: String(lic.machine ?? "local"),
    };
  }
  if (status === "active") {
    return {
      status: "active",
      plan: String(lic.plan ?? "Hospital Edition"),
      serial: String(lic.serial ?? ""),
      daysLeft: 9999,
      seats: Number(lic.seats ?? 5),
      activatedAt,
      owner: String(lic.owner ?? "Dr. Mamon Aminyar"),
      machine: String(lic.machine ?? "local"),
    };
  }
  // Trial counts from the very first record ever created in this installation.
  const first = hGet<{ created_at: string }>(
    "SELECT created_at FROM hms_users ORDER BY created_at ASC LIMIT 1"
  );
  const start = first ? new Date(first.created_at).getTime() : Date.now();
  const elapsed = Math.floor((Date.now() - start) / 864e5);
  const daysLeft = Math.max(0, TRIAL_DAYS - elapsed);
  return {
    status: daysLeft > 0 ? "trial" : "expired",
    plan: String(lic.plan ?? `Trial (${TRIAL_DAYS} days)`),
    serial: String(lic.serial ?? ""),
    daysLeft,
    seats: Number(lic.seats ?? 5),
    activatedAt,
    owner: String(lic.owner ?? "Dr. Mamon Aminyar"),
    machine: String(lic.machine ?? "local"),
  };
}

export function listSerials() {
  return hAll<{
    id: string; serial: string; plan: string; seats: number; issued_at: string;
    activated_at: string | null; hospital: string | null; machine: string | null; status: string; note: string | null;
  }>("SELECT * FROM hms_licenses ORDER BY issued_at DESC LIMIT 60");
}
