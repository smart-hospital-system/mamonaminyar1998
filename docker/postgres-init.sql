\set ON_ERROR_STOP on
\set owner_password `cat /run/secrets/owner_password`
\set app_password `cat /run/secrets/app_password`
CREATE ROLE ash_owner LOGIN PASSWORD :'owner_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE ash_app LOGIN PASSWORD :'app_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO ash_owner;
GRANT USAGE ON SCHEMA public TO ash_app;
GRANT CONNECT ON DATABASE ash TO ash_owner, ash_app;
SET ROLE ash_owner;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ash_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO ash_app;
RESET ROLE;
