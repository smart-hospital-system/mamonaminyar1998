import { Beaker } from "lucide-react";
import { Panel, SectionTitle, Stat } from "@/components/hms/ui";
import { requireHmsPage } from "@/lib/hms/auth";
import { tx } from "@/lib/hms/i18n";
import { getLang } from "@/lib/hms/lang-server";

import { readFileSync } from "node:fs";
import { join } from "node:path";
import { hmsReady } from "@/lib/hms/db";
import { listMedicines, listPrescriptions } from "@/lib/hms/queries";
import { digitsOf, money } from "@/lib/hms/format";
import { PharmacyBoard } from "./board";

export const dynamic = "force-dynamic";

type StoreLine = { sku: string; name: string; nameFa: string; className: string; classNameFa: string; expiry: string; daysToExpiry: number; nearExpiry: boolean; stock: number; reorderLevel: number; formLabel: string; pack: string };
type StoreCatalogue = { totals: { items: number; nearExpiry: number; lowStock: number }; items: StoreLine[] };

/**
 * The store catalogue is generated by `npm run hms:store`. It is read here so
 * the expiry watch shows real medicine names rather than counts alone. If the
 * file is missing (a fresh clone before generation) the panel simply hides.
 */
function readStore(): StoreCatalogue | null {
  try {
    return JSON.parse(readFileSync(join(process.cwd(), "data", "store-catalogue.json"), "utf8")) as StoreCatalogue;
  } catch {
    return null;
  }
}

export default async function PharmacyPage({ searchParams }: { searchParams: Promise<{ tab?: string; q?: string }> }) {
  const user = await requireHmsPage(["admin", "pharmacist", "nurse"]);
  await hmsReady();
  const lang = await getLang();
  const tr = (en: string, fa: string, vars?: Record<string, string | number>) => tx(lang, en, fa, vars);
  const sp = await searchParams;
  const meds = listMedicines({});
  const rx = listPrescriptions({ limit: 100 });
  const low = meds.filter((m) => m.stock <= m.reorder_level);
  const expiring = meds.filter((m) => m.expiry && new Date(m.expiry).getTime() < Date.now() + 60 * 864e5);
  const stockValue = meds.reduce((a, m) => a + m.stock * m.unit_price, 0);
  const store = readStore();
  const nearExpiry = store ? store.items.filter((i) => i.nearExpiry).sort((a, b) => a.daysToExpiry - b.daysToExpiry) : [];

  return (
    <div className="space-y-3.5">
      <div className="grid grid-cols-2 gap-2.5 sm:grid-cols-4">
        <Stat label={tr("Dispensing queue", "صف تحویل دوا")} value={digitsOf(lang, rx.filter((r) => ["signed", "pending"].includes(r.status)).length)} hint={tr("Signed prescriptions", "نسخه‌های امضاشده")} tone="warn" icon={<Beaker size={14} />} />
        <Stat label={tr("Below reorder level", "کمتر از حد سفارش")} value={digitsOf(lang, low.length)} hint={low.slice(0, 2).map((l) => l.name).join(", ") || tr("All healthy", "همه کافی است")} tone={low.length ? "bad" : "good"} />
        <Stat label={tr("Expiring ≤ 60 days", "انقضا در ۶۰ روز")} value={digitsOf(lang, expiring.length)} hint={tr("Rotate stock now", "موجودی را همین حالا بچرخانید")} tone={expiring.length ? "warn" : "good"} />
        <Stat label={tr("Stock value", "ارزش موجودی")} value={money(stockValue, lang)} hint={tr("{n} lines", "{n} قلم", { n: digitsOf(lang, meds.length) })} tone="brand" />
      </div>
      {store && (
        <Panel>
          <SectionTitle
            title={tr("Expiry watch — store catalogue", "پایش انقضا — کاتالوگ انبار")}
            subtitle={tr(
              "From the {n}-line store file: {e} lines expire within 90 days, {l} are below reorder level.",
              "از فایل {n} قلمی انبار: {e} قلم در ۹۰ روز منقضی می‌شود، {l} قلم کمتر از حد سفارش است.",
              { n: digitsOf(lang, store.totals.items), e: digitsOf(lang, store.totals.nearExpiry), l: digitsOf(lang, store.totals.lowStock) }
            )}
            action={
              <span className="text-[11px]" style={{ color: "var(--hms-muted)" }}>
                {tr("oldest first", "قدیمی‌ترین اول")}
              </span>
            }
          />
          <div className="mt-2 grid gap-2 md:grid-cols-2">
            <ul className="space-y-1">
              {nearExpiry.slice(0, 8).map((i) => (
                <li key={i.sku} className="flex items-baseline justify-between gap-2 rounded-lg border px-2.5 py-1.5" style={{ borderColor: "var(--hms-border)", background: "var(--hms-surface-2)" }}>
                  <span className="min-w-0">
                    <span className="block truncate text-[13px]" style={{ color: "var(--hms-ink)" }}>
                      {lang === "fa" && i.nameFa ? i.nameFa : i.name}
                    </span>
                    <span className="block text-[11px]" style={{ color: "var(--hms-muted)" }}>
                      {i.sku} · {i.formLabel} · {i.pack} · {lang === "fa" ? i.classNameFa : i.className}
                    </span>
                  </span>
                  <span className="shrink-0 text-[11px] font-medium tabular-nums" style={{ color: i.daysToExpiry <= 75 ? "#c0392b" : "#a8630a" }}>
                    {digitsOf(lang, i.daysToExpiry)} {tr("days", "روز")}
                  </span>
                </li>
              ))}
            </ul>
            <div className="rounded-lg border p-2.5" style={{ borderColor: "var(--hms-border)", background: "var(--hms-surface-2)" }}>
              <p className="text-[12px] font-semibold" style={{ color: "var(--hms-ink)" }}>
                {tr("What to do with the near-expiry batch", "با دستهٔ نزدیک انقضا چه کنیم")}
              </p>
              <ol className="mt-1 list-inside list-decimal space-y-1 text-[11px]" style={{ color: "var(--hms-muted)" }}>
                <li>{tr("Rotate to the front of the shelf and dispense these first.", "به جلوی قفسه منتقل و اول تحویل داده شوند.")}</li>
                <li>{tr("Tell the prescriber before a long course needs more than 90 days of stock.", "پیش از نسخهٔ طولانی‌مدت، پزشک را آگاه کنید.")}</li>
                <li>{tr("Return to the supplier or quarantine 30 days before expiry; never dispense after the date.", "۳۰ روز پیش از انقضا به تأمین‌کننده برگردانید یا قرنطینه کنید.")}</li>
                <li>{tr("Record the write-off in the audit trail.", "حذف موجودی را در ثبت بازبینی ثبت کنید.")}</li>
              </ol>
            </div>
          </div>
        </Panel>
      )}

      <Panel>
        <SectionTitle
          title={tr("Pharmacy counter", "کانتر دواخانه")}
          subtitle={tr("Dispense against a prescription (stock is decremented automatically) or manage inventory and expiry.", "دوا را مطابق نسخه تحویل دهید (موجودی خودکار کم می‌شود) یا موجودی و انقضا را مدیریت کنید.")}
          icon={<Beaker size={14} />}
        />
        <PharmacyBoard
          prescriptions={rx.map((r) => ({ id: r.id, rx_no: r.rx_no, patient_name: r.patient_name, patient_mrn: r.patient_mrn, diagnosis: r.diagnosis, status: r.status, items: r.items, created_at: r.created_at, doctor_name: r.doctor_name }))}
          medicines={meds}
          initialTab={sp.tab === "stock" ? "stock" : sp.tab === "expiry" ? "expiry" : "queue"}
          initialQuery={sp.q ?? ""}
        />
      </Panel>
    </div>
  );
}
